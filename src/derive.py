"""Derive the tractor-semitrailer models and export them as MATLAB functions.

1. Nonlinear planar model by Lagrange's equations in minimal coordinates
   q = [X, Y, psi1, phi]  (tractor CG position, tractor heading, articulation angle)
   psi2 = psi1 - phi.  Axle forces are given in each body's frame.
   Output: M(q) qdd = rhs(q, qd, forces)
2. Linear single-track model (constant speed u, small angles), states
   x = [v1, r1, phid, phi], inputs [M1, M2, delta].
"""
import sympy as sp
from sympy.printing.octave import octave_code

import os
OUT = os.path.dirname(os.path.abspath(__file__)) + os.sep

# ---------------- nonlinear model ----------------
t = sp.symbols('t')
X, Y, psi1, phi = [sp.Function(n)(t) for n in ('X', 'Y', 'psi1', 'phi')]
m1, I1, m2, I2, a1, b1, c1, d2, e2 = sp.symbols('m1 I1 m2 I2 a1 b1 c1 d2 e2', positive=True)
# body-frame axle forces (already rotated from wheel frame) and yaw moments from L/R splits
Fxf, Fyf, Fxr, Fyr, Fxt, Fyt, Mz1, Mz2 = sp.symbols('Fxf Fyf Fxr Fyr Fxt Fyt Mz1 Mz2')

psi2 = psi1 - phi
e1 = sp.Matrix([sp.cos(psi1), sp.sin(psi1)]); n1 = sp.Matrix([-sp.sin(psi1), sp.cos(psi1)])
e2v = sp.Matrix([sp.cos(psi2), sp.sin(psi2)]); n2 = sp.Matrix([-sp.sin(psi2), sp.cos(psi2)])
p1 = sp.Matrix([X, Y])
ph = p1 - c1 * e1
p2 = ph - d2 * e2v
pf = p1 + a1 * e1
pr = p1 - b1 * e1
pt = p2 - e2 * e2v

q = [X, Y, psi1, phi]
qd = [sp.diff(v, t) for v in q]
qdd = [sp.diff(v, t, 2) for v in q]

v1w = p1.diff(t); v2w = p2.diff(t)
T = sp.Rational(1, 2) * (m1 * v1w.dot(v1w) + I1 * sp.diff(psi1, t)**2
                         + m2 * v2w.dot(v2w) + I2 * sp.diff(psi2, t)**2)

def genforce(Fbody_x, Fbody_y, ex, ny, p):
    Fw = Fbody_x * ex + Fbody_y * ny
    return [Fw.dot(p.diff(qi)) for qi in q]

Q = [0] * 4
for Fx_, Fy_, ex, ny, p in [(Fxf, Fyf, e1, n1, pf), (Fxr, Fyr, e1, n1, pr), (Fxt, Fyt, e2v, n2, pt)]:
    g = genforce(Fx_, Fy_, ex, ny, p)
    Q = [Q[i] + g[i] for i in range(4)]
for Mz, ang in [(Mz1, psi1), (Mz2, psi2)]:
    Q = [Q[i] + Mz * sp.diff(ang, qi) for i, qi in enumerate(q)]

L = T
eoms = [sp.diff(sp.diff(L, qd[i]), t) - sp.diff(L, q[i]) - Q[i] for i in range(4)]
Mmat = sp.Matrix(4, 4, lambda i, j: sp.diff(eoms[i], qdd[j]))
rhs = sp.Matrix([-(eoms[i].subs({qdd[j]: 0 for j in range(4)})) for i in range(4)])

# replace functions by plain symbols for code generation
qs = sp.symbols('X Y psi1 phi'); qds = sp.symbols('Xd Yd psi1d phid')
rep = {}
for i in range(4):
    rep[qd[i]] = qds[i]
for i in range(4):
    rep[q[i]] = qs[i]
Mmat = sp.simplify(Mmat.subs(rep))
rhs = sp.simplify(rhs.subs(rep))

def write_fn(name, args_doc, body, outs):
    with open(OUT + name + '.m', 'w') as f:
        f.write(body)

params_unpack = ("m1=P.m1; I1=P.I1; m2=P.m2; I2=P.I2; a1=P.a1; b1=P.b1; c1=P.c1; d2=P.d2; e2=P.e2;\n")

subexpr, (Mred, rred) = sp.cse([Mmat, rhs], symbols=sp.numbered_symbols('w'))
lines = []
for s, e in subexpr:
    lines.append(f"  {s} = {octave_code(e)};")
code = "function [M, rhs] = eom_nonlinear(q, qd, F, P)\n"
code += "%EOM_NONLINEAR  Mass matrix and right-hand side of the planar tractor-semitrailer model.\n"
code += "%  Generated by derive.py (SymPy, Lagrange's equations, minimal coordinates).\n"
code += "%  q  = [X; Y; psi1; phi]   tractor CG position (m), tractor heading (rad), articulation angle (rad)\n"
code += "%  qd = time derivative of q\n"
code += "%  F  = [Fxf Fyf Fxr Fyr Fxt Fyt Mz1 Mz2]  axle forces in body frames (N) and L/R yaw moments (N m)\n"
code += "%  Solve qdd = M \\ rhs.\n"
code += "  X=q(1); Y=q(2); psi1=q(3); phi=q(4); %#ok<NASGU>\n"
code += "  Xd=qd(1); Yd=qd(2); psi1d=qd(3); phid=qd(4); %#ok<NASGU>\n"
code += "  Fxf=F(1); Fyf=F(2); Fxr=F(3); Fyr=F(4); Fxt=F(5); Fyt=F(6); Mz1=F(7); Mz2=F(8);\n"
code += "  " + params_unpack
code += "\n".join(lines) + "\n"
code += "  M = zeros(4,4); rhs = zeros(4,1);\n"
for i in range(4):
    for j in range(4):
        code += f"  M({i+1},{j+1}) = {octave_code(Mred[i, j])};\n"
for i in range(4):
    code += f"  rhs({i+1}) = {octave_code(rred[i])};\n"
code += "end\n"
open(OUT + 'eom_nonlinear.m', 'w').write(code)

# ---------------- linear single-track model ----------------
v1, r1, phd, ph_, M1, M2, de = sp.symbols('v1 r1 phid phi M1 M2 delta')
dv1, dr1, dphd, dph, Fh = sp.symbols('dv1 dr1 dphd dph Fh')
Cf, Cr, Ct, u = sp.symbols('Cf Cr Ct u', positive=True)
r2 = r1 - phd; dr2 = dr1 - dphd
v2 = v1 - c1 * r1 - d2 * r2 + u * ph_
dv2 = dv1 - c1 * dr1 - d2 * dr2 + u * phd
Fyf_l = Cf * (de - (v1 + a1 * r1) / u); Fyr_l = -Cr * (v1 - b1 * r1) / u; Fyt_l = -Ct * (v2 - e2 * r2) / u
eqs = [m1 * (dv1 + u * r1) - (Fyf_l + Fyr_l - Fh), I1 * dr1 - (a1 * Fyf_l - b1 * Fyr_l + c1 * Fh + M1),
       m2 * (dv2 + u * r2) - (Fyt_l + Fh), I2 * dr2 - (d2 * Fh - e2 * Fyt_l + M2), dph - phd]
sol = sp.solve(eqs, [dv1, dr1, dphd, dph, Fh], dict=True)[0]
f = sp.Matrix([sol[dv1], sol[dr1], sol[dphd], sol[dph]])
A = sp.simplify(f.jacobian([v1, r1, phd, ph_]))
B = sp.simplify(f.jacobian([M1, M2, de]))
subexpr, (Ar, Br) = sp.cse([A, B], symbols=sp.numbered_symbols('w'))
code = "function [A, B] = lin_model(u, P)\n"
code += "%LIN_MODEL  Linear single-track tractor-semitrailer model at constant speed u (m/s).\n"
code += "%  Generated by derive.py.  x = [v1; r1; phid; phi], inputs [M1; M2; delta]\n"
code += "%  v1 tractor lateral velocity (m/s), r1 tractor yaw rate (rad/s), phi articulation angle (rad)\n"
code += "%  M1, M2 control yaw moments on tractor and semitrailer (N m), delta front steer angle (rad)\n"
code += "  " + params_unpack
code += "  Cf=P.Cf; Cr=P.Cr; Ct=P.Ct;\n"
code += "\n".join(f"  {s} = {octave_code(e)};" for s, e in subexpr) + "\n"
code += "  A = zeros(4,4); B = zeros(4,3);\n"
for i in range(4):
    for j in range(4):
        code += f"  A({i+1},{j+1}) = {octave_code(Ar[i, j])};\n"
    for j in range(3):
        code += f"  B({i+1},{j+1}) = {octave_code(Br[i, j])};\n"
code += "end\n"
open(OUT + 'lin_model.m', 'w').write(code)
print('written')
